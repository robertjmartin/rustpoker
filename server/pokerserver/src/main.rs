// self-contained HTML file, so the whole app is served from a single route.
const CLIENT_HTML: &str = include_str!("../static/client.html");

#[derive(Debug, Clone, Serialize)]
struct User {
    id: UserId,
    name: String,
    balance: u32,
}

#[derive(Clone)]
struct AppState {
    users: Arc<Mutex<HashMap<UserId, User>>>,
    table_tx: mpsc::Sender<TableCommand>,
}

// The long-running task. It exits when all Senders are dropped.
async fn worker(mut rx: mpsc::Receiver<TableCommand>) {
    let mut table = Table::new(8);
    let mut timer = time::interval(TICK_INTERVAL);
    timer.set_missed_tick_behavior(MissedTickBehavior::Skip);
    let mut connections: HashMap<UserId, mpsc::Sender<String>> = HashMap::new();
    let mut seat_map: HashMap<UserId, u8> = HashMap::new();

    loop {
        select! {
            recv = rx.recv() => {
                match recv {
                    Some(table_command) => {
                        match table_command.cmd {
                            TableCommands::Join(join_cmd) => {
                                connections.insert(table_command.user_id, join_cmd.tx);
                                // A joining or reconnecting client gets the whole table once,
                                // so it does not have to rebuild it from the event stream.
                                let viewer = seat_map.get(&table_command.user_id).copied();
                                if !send_snapshot(&connections, table_command.user_id, table.snapshot(viewer)).await {
                                    connections.remove(&table_command.user_id);
                                }
                            },
                            TableCommands::Leave => {
                                if let Some(seat) = seat_map.remove(&table_command.user_id) {
                                    table.leave(seat);
                                }
                                connections.remove(&table_command.user_id);
                            }
                            TableCommands::Disconnect(disconnect) => {
                                // Ignore a late disconnect when this user already
                                // reconnected on a newer socket.
                                let superseded = connections
                                    .get(&table_command.user_id)
                                    .is_some_and(|current| !current.same_channel(&disconnect.tx));
                                if !superseded {
                                    // Stand the player up so an abandoned seat
                                    // cannot stall the table.
                                    connections.remove(&table_command.user_id);
                                    if let Some(seat) = seat_map.remove(&table_command.user_id) {
                                        table.leave(seat);
                                    }
                                }
                            },
                            TableCommands::HoleCards => {
                                if let Some(seat) = seat_map.get(&table_command.user_id).copied() {
                                    if let Some(hole_cards) = table.hole_cards(seat) {
                                        if !send_private(&connections, table_command.user_id, seat, hole_cards.cards).await {
                                            connections.remove(&table_command.user_id);
                                        }
                                    }
                                }
                            },
                            TableCommands::Action(table_action) => {
                                match table_action.action {
                                    TableAction::Sit(sit_action) => {
                                        // Sitting twice would leak a seat and lose track of the first one.
                                        if !seat_map.contains_key(&table_command.user_id) {
                                            if let Some(seat) = table.sit(sit_action.bank_amount) {
                                                seat_map.insert(table_command.user_id, seat);
                                            }
                                        }
                                    },
                                    TableAction::Stand => {
                                        if let Some(seat) = seat_map.remove(&table_command.user_id) {
                                            table.leave(seat);
                                        }
                                    },
                                    TableAction::Bet(bet_action) => {
                                        if let Some(seat) = seat_map.get(&table_command.user_id) {
                                            table.bet(*seat, bet_action.bet_amount);
                                        }
                                    },
                                    TableAction::Check => {
                                        if let Some(seat) = seat_map.get(&table_command.user_id) {
                                            table.check(*seat);
                                        }
                                    },
                                    TableAction::Fold => {
                                        if let Some(seat) = seat_map.get(&table_command.user_id) {
                                            table.fold(*seat);
                                        }
                                    },
                                }
                            },
                        }

                        let events = table.drain_events();
                        broadcast(&mut connections, events).await;
                        send_hole_cards(&mut connections, &seat_map, &mut table).await;
                    },
                    None => break,                    
                }
            }
            _ = timer.tick() => {
                table.process();
                let events = table.drain_events();
                broadcast(&mut connections, events).await;
                send_hole_cards(&mut connections, &seat_map, &mut table).await;
            }
        }
    }
}

// Serialise each table event once and push the same JSON to every joined client.
async fn broadcast(connections: &mut HashMap<UserId, mpsc::Sender<String>>, events: Vec<GameEvent>) {
    let mut dead: Vec<UserId> = Vec::new();

    for event in events {
        let json = match serde_json::to_string(&event) {
            Ok(json) => json,
            Err(e) => {
                eprintln!("failed to encode game event: {e}");
                continue;
            }
        };

        for (user_id, tx) in connections.iter() {
            if tx.send(json.clone()).await.is_err() {
                dead.push(*user_id);
            }
        }
    }

    // A failed send means the connection task is gone; stop tracking it.
    for user_id in dead {
        connections.remove(&user_id);
    }
}

// Private message: only the player holding this seat ever receives it.
#[derive(Serialize)]
struct HoleCardsMessage {
    event: &'static str,
    seat: u8,
    cards: [Card; 2],
}

// Private message: the whole table as this player is allowed to see it.
#[derive(Serialize)]
struct SnapshotMessage {
    event: &'static str,
    #[serde(flatten)]
    snapshot: TableSnapshot,
}

// Serialise one frame and push it to one connection. Returns false when that
// connection is gone.
async fn send_frame<T: Serialize>(
    connections: &HashMap<UserId, mpsc::Sender<String>>,
    user_id: UserId,
    frame: &T,
) -> bool {
    let json = match serde_json::to_string(frame) {
        Ok(json) => json,
        Err(e) => {
            eprintln!("failed to encode private frame: {e}");
            return true;
        }
    };

    match connections.get(&user_id) {
        Some(tx) => tx.send(json).await.is_ok(),
        None => true,
    }
}

// Send one hand to one player. Returns false if that connection is gone.
async fn send_private(
    connections: &HashMap<UserId, mpsc::Sender<String>>,
    user_id: UserId,
    seat: u8,
    cards: [Card; 2],
) -> bool {
    send_frame(connections, user_id, &HoleCardsMessage { event: "holeCards", seat, cards }).await
}

// Send one connection the current table. Returns false if it is gone.
async fn send_snapshot(
    connections: &HashMap<UserId, mpsc::Sender<String>>,
    user_id: UserId,
    snapshot: TableSnapshot,
) -> bool {
    send_frame(connections, user_id, &SnapshotMessage { event: "snapshot", snapshot }).await
}

// Send each newly dealt hand to the seat that holds it.
async fn send_hole_cards(
    connections: &mut HashMap<UserId, mpsc::Sender<String>>,
    seat_map: &HashMap<UserId, u8>,
    table: &mut Table,
) {
    let mut dead: Vec<UserId> = Vec::new();

    for (seat, hole_cards) in table.drain_hole_cards() {
        let Some(user_id) = seat_map.iter().find(|(_, s)| **s == seat.0).map(|(u, _)| *u) else {
            continue;
        };
        if !send_private(connections, user_id, seat.0, hole_cards.cards).await {
            dead.push(user_id);
        }
    }

    for user_id in dead {
        connections.remove(&user_id);
    }
}

#[tokio::main]
async fn main() {
    let (table_tx, table_rx) = mpsc::channel(100);
    tokio::spawn(worker(table_rx));
    
    let state = AppState {
        users: Arc::new(Mutex::new(HashMap::new())),  //todo consider RwLock
        table_tx,
    };

    let app = Router::new()
        .route("/", get(client_page))
        .route("/test", get(test_page))
        .route("/ping", get(|| async { "{\"status\": \"ok\"}" }))
        .route("/ws", get(ws_handler))
        .route("/register", post(handle_register))
        .route("/user/{id}" , get(handle_getuser))
        .route("/usercount", get(handle_usercount))
        .with_state(state);

    let listener = tokio::net::TcpListener::bind("0.0.0.0:3000")
        .await
        .unwrap();
    println!("listening on {}", listener.local_addr().unwrap());

    axum::serve(listener, app).await.unwrap();
}

#[derive(Deserialize)]
struct HandleRegisterBody {
    name: String,
}

async fn handle_register(State(state): State<AppState>, Json(payload): Json<HandleRegisterBody>) -> (StatusCode, Json<User>)  {
    let new_id = client_command::UserId(uuid::Uuid::new_v4());
    
    let new_user = User {
        id: new_id,
        name: payload.name,
        balance: 1000,
    };

    state.users.lock().unwrap().insert(new_id, new_user.clone());
    
    (StatusCode::CREATED, Json(new_user))
}

async fn handle_getuser(State(state): State<AppState>, Path(id): Path<UserId>) -> Response {
    match state.users.lock().unwrap().get(&id) {
        Some(u) => Json(u.clone()).into_response(),
        None => StatusCode::NOT_FOUND.into_response(),
    }
}

#[derive(Serialize)]
struct HandleUserCountResult {
    count: usize,
}

async fn handle_usercount(State(state): State<AppState>) -> (StatusCode, Json<HandleUserCountResult>) {
    let result = HandleUserCountResult {
        count: state.users.lock().unwrap().len(),
    };
    
    (StatusCode::OK, Json(result))
}

// The client is generated into one HTML file and embedded at compile time, so
// a browser that caches an older copy would run a stale client against a newer
// server. Never let `/` be cached.
async fn client_page() -> impl IntoResponse {
    ([(header::CACHE_CONTROL, "no-store")], Html(CLIENT_HTML))
}

async fn test_page() -> impl IntoResponse {
    ([(header::CACHE_CONTROL, "no-store")], Html(CLIENT_TEST_HTML))
}

async fn ws_handler(State(state): State<AppState>, ws: WebSocketUpgrade) -> impl IntoResponse {
   ws.on_upgrade(move |socket| handle_socket(socket, state))
}

async fn process_client_command(state: &AppState, auth_user_id: &mut Option<UserId>, tx: &mpsc::Sender<String>, cmd: ClientCommand) -> ClientResponse {
    match cmd {
        ClientCommand::SetAuthentication(cmd) => {
            let users = state.users.lock().unwrap();
            if users.contains_key(&cmd.user_id) {
                *auth_user_id = Some(cmd.user_id);
                ClientResponse::Success(ClientCommandResponse::SetAuthentication(AuthenticationContent {user_id: cmd.user_id}))
            } else {
                ClientResponse::Error(ClientCommandError::Unknown)
            }       
        },
        ClientCommand::GetAuthentication => match auth_user_id {
            Some(user_id) => ClientResponse::Success(ClientCommandResponse::SetAuthentication(AuthenticationContent {user_id: *user_id})),
            None => ClientResponse::Error(ClientCommandError::Unknown),
        },
        ClientCommand::GetHoleCards => match auth_user_id {
            Some(user_id) => {
                state.table_tx.send(TableCommand {user_id: *user_id, cmd: TableCommands::HoleCards} ).await;
                ClientResponse::Success(ClientCommandResponse::GetHoleCards)
            }
            None => ClientResponse::Error(ClientCommandError::NotAuthenticated),
        },
        ClientCommand::JoinTable(cmd) => {
            match auth_user_id {
                Some(user_id) => {
                    state.table_tx.send(TableCommand {user_id: *user_id, cmd: TableCommands::Join(JoinTableCommand{tx: tx.clone()})} ).await;
                    ClientResponse::Success(ClientCommandResponse::JoinTable)
                },
                None => ClientResponse::Error(ClientCommandError::NotAuthenticated), 
            }
        },
        ClientCommand::LeaveTable => match auth_user_id {
            Some(user_id) => {
                state.table_tx.send(TableCommand {user_id: *user_id, cmd: TableCommands::Leave} ).await;
                ClientResponse::Success(ClientCommandResponse::LeaveTable)
            }
            None => ClientResponse::Error(ClientCommandError::NotAuthenticated),
        },
        ClientCommand::Table(cmd) => {
            match auth_user_id {
                Some(user_id) => {
                    //todo handle cmd.table_id
                    state.table_tx.send(TableCommand {user_id: *user_id, cmd: TableCommands::Action(ActionTableCommand {action: cmd.action})}).await;
                    ClientResponse::Success(ClientCommandResponse::Table)
                },
                None => ClientResponse::Error(ClientCommandError::NotAuthenticated), 
            }
        }
    }
}

async fn handle_socket(mut socket: WebSocket, state: AppState) {
    let (tx, mut rx) = mpsc::channel::<String>(100);
    let mut auth_user_id: Option<UserId> = None;

    // A browser that loses its network or is killed can leave a socket that
    // never closes from this side: writes keep buffering and the player is
    // never stood up. Ping it and drop the socket when it stops answering, so
    // the seat is freed and the browser reconnects.
    let mut keepalive = time::interval(KEEPALIVE_INTERVAL);
    keepalive.set_missed_tick_behavior(MissedTickBehavior::Delay);
    let mut last_seen = time::Instant::now();

    loop {
        tokio::select! {
            msg = socket.recv() => {
                last_seen = time::Instant::now();
                match msg {
                    Some(Ok(Message::Close(_))) | None => break,
                    Some(Ok(msg)) => {
                        if let Message::Text(text) = msg {
                            let response: Option<ClientMessageResponse> = match serde_json::from_str::<ClientMessage>(&text) {
                                Ok(msg) => {
                                    Some(ClientMessageResponse {
                                        id: msg.id,
                                        response: process_client_command(&state, &mut auth_user_id, &tx, msg.command).await,
                                    })
                                },
                                Err(e) => {
                                    eprintln!("parse error: {e}");
                                    None
                                }
                            };

                            if let Some(response) = response {
                                let json = serde_json::to_string(&response).unwrap();
                                socket.send(Message::Text(json.into())).await;
                            }                                                
                        }
                    },                    
                    Some(Err(e)) => {
                        eprintln!("websocket error: {e}");
                        break;
                    }
                }
            }
            event = rx.recv() => {
                match event {
                    Some(json) => {
                        if socket.send(Message::Text(json.into())).await.is_err() {
                            break;
                        }
                    }
                    // The worker dropped the sender: there is no table left to listen to.
                    None => break,
                }
            }
            _ = keepalive.tick() => {
                // Browsers answer a ping with a pong, so silence means the peer
                // is gone. Give it a couple of intervals before giving up.
                if last_seen.elapsed() > KEEPALIVE_TIMEOUT {
                    break;
                }
                if socket.send(Message::Ping(Vec::new().into())).await.is_err() {
                    break;
                }
            }
        }
    }

    // The socket is gone. Tell the worker so the seat is freed even when no
    // other traffic would have noticed the dead connection.
    if let Some(user_id) = auth_user_id {
        let _ = state
            .table_tx
            .send(TableCommand {
                user_id,
                cmd: TableCommands::Disconnect(DisconnectCommand { tx }),
            })
            .await;
    }
}