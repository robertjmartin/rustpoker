/// The table's clock and hand-pacing resolution. `process()` also counts the
/// per-turn deadline in these ticks.
const TICK_INTERVAL: Duration = Duration::from_secs(1);

/// How often an idle socket is pinged, and how long it may stay silent before
/// it is treated as gone.
const KEEPALIVE_INTERVAL: Duration = Duration::from_secs(10);
const KEEPALIVE_TIMEOUT: Duration = Duration::from_secs(25);

const CLIENT_TEST_HTML: &str = include_str!("../static/test.html");
